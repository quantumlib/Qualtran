TEST(FixedPrecisionAngle128, to_bool) {
    ASSERT_TRUE((FixedPrecisionAngle128{1, 0}));
    ASSERT_TRUE((FixedPrecisionAngle128{0, 1}));
    ASSERT_TRUE((FixedPrecisionAngle128{2, 3}));
    ASSERT_FALSE((FixedPrecisionAngle128{0, 0}));
}

TEST(FixedPrecisionAngle128, raw_constructor) {
    FixedPrecisionAngle128 a{11, 13};
    ASSERT_EQ(a.words[0], 11);
    ASSERT_EQ(a.words[1], 13);
}

TEST(FixedPrecisionAngle128, equality) {
    ASSERT_EQ((FixedPrecisionAngle128{0, 0}), (FixedPrecisionAngle128{0, 0}));

    ASSERT_NE((FixedPrecisionAngle128{0, 1}), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ((FixedPrecisionAngle128{0, 1}), (FixedPrecisionAngle128{0, 1}));
    ASSERT_NE((FixedPrecisionAngle128{0, 0}), (FixedPrecisionAngle128{0, 1}));

    ASSERT_NE((FixedPrecisionAngle128{1, 0}), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ((FixedPrecisionAngle128{1, 0}), (FixedPrecisionAngle128{1, 0}));
    ASSERT_NE((FixedPrecisionAngle128{0, 0}), (FixedPrecisionAngle128{1, 0}));

    ASSERT_NE((FixedPrecisionAngle128{1, 1}), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ((FixedPrecisionAngle128{1, 1}), (FixedPrecisionAngle128{1, 1}));
    ASSERT_NE((FixedPrecisionAngle128{0, 0}), (FixedPrecisionAngle128{1, 1}));

    ASSERT_EQ((FixedPrecisionAngle128{11, 13}), (FixedPrecisionAngle128{11, 13}));
    ASSERT_NE((FixedPrecisionAngle128{2, 3}), (FixedPrecisionAngle128{5, 11}));
}

TEST(FixedPrecisionAngle128, zero) {
    FixedPrecisionAngle128 zero{};
    ASSERT_EQ(zero.words[0], 0);
    ASSERT_EQ(zero.words[1], 0);
    ASSERT_EQ(zero.to_decimal_half_turns(), "0.0");
    ASSERT_EQ(FixedPrecisionAngle128(), FixedPrecisionAngle128());
    ASSERT_EQ(FixedPrecisionAngle128(FixedPrecisionAngle128{1, 2}), (FixedPrecisionAngle128{1, 2}));
}

TEST(FixedPrecisionAngle128, out) {
    FixedPrecisionAngle128 angle{8136502895309290460ULL, 9501696840481732625ULL};
    std::string_view expected =
        "1."
        "03017603567489479854749682993628867741453762562080331644977355037819211920294764045329116708415995162795297801"
        "494598388671875";
    ASSERT_EQ(angle.str(), std::string(expected) + "π");
    ASSERT_EQ(angle.to_decimal_half_turns(), expected);
    std::stringstream ss;
    ss << angle;
    ASSERT_EQ(ss.str(), std::string(expected) + "π");

    RaiiTempNamedFile tmp;
    FILE *f = fopen(tmp.path.c_str(), "w");
    angle.write_decimal_half_turns_to(f);
    fclose(f);
    ASSERT_EQ(tmp.read_contents(), expected);
}

TEST(FixedPrecisionAngle128, from_double) {
    ASSERT_EQ(FixedPrecisionAngle128::from_half_turns_exact_double(0.0), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ(FixedPrecisionAngle128::from_half_turns_exact_double(-0.0), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ(FixedPrecisionAngle128::from_half_turns_exact_double(2.0), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ(FixedPrecisionAngle128::from_half_turns_exact_double(-10.0), (FixedPrecisionAngle128{0, 0}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(1.0), (FixedPrecisionAngle128{0, uint64_t{1} << 63}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(0.5), (FixedPrecisionAngle128{0, uint64_t{1} << 62}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(-0.5), (FixedPrecisionAngle128{0, uint64_t{3} << 62}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(-2 * 5.25),
        (FixedPrecisionAngle128{0, uint64_t{3} << 62}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(2 * 5.75), (FixedPrecisionAngle128{0, uint64_t{3} << 62}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2 * 131, -63)),
        (FixedPrecisionAngle128{0, 262}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2 * 131, -64)),
        (FixedPrecisionAngle128{0, 131}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2 * 131, -65)),
        (FixedPrecisionAngle128{uint64_t{1} << 63, 65}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2.0, -64)), (FixedPrecisionAngle128{0, 1}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2.0, -65)),
        (FixedPrecisionAngle128{uint64_t{1} << 63, 0}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2.0, -128)), (FixedPrecisionAngle128{1, 0}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2.0, -128)), (FixedPrecisionAngle128{1, 0}));
    ASSERT_EQ(
        FixedPrecisionAngle128::from_half_turns_exact_double(-std::ldexp(2.0, -128)),
        (FixedPrecisionAngle128{UINT64_MAX, UINT64_MAX}));

    ASSERT_THROW(
        { FixedPrecisionAngle128::from_half_turns_exact_double(std::ldexp(2.0, -129)); }, std::invalid_argument);
    ASSERT_THROW(
        { FixedPrecisionAngle128::from_half_turns_exact_double(std::numeric_limits<double>::quiet_NaN()); },
        std::invalid_argument);
    ASSERT_THROW(
        { FixedPrecisionAngle128::from_half_turns_exact_double(std::numeric_limits<double>::infinity()); },
        std::invalid_argument);
    ASSERT_THROW(
        { FixedPrecisionAngle128::from_half_turns_exact_double(-std::numeric_limits<double>::infinity()); },
        std::invalid_argument);
}

